//! The `<area>.manifest` format that binds each variant to its sources, PTX and cubins

use std::collections::BTreeMap;
use std::fmt::Write as _;

use color_eyre::eyre::{Result, bail, eyre};

use crate::{CubinArch, Project, Tier};

/// Contents of `<area>.manifest`: one section per variant, baseline first
#[derive(Debug, Default, PartialEq, Eq)]
pub(crate) struct Manifest {
    pub(crate) ptxas: Option<String>,
    pub(crate) ptxas_flags: Option<String>,
    pub(crate) variants: Vec<ManifestVariant>,
}

#[derive(Debug, PartialEq, Eq)]
pub(crate) struct ManifestVariant {
    pub(crate) tier: Tier,
    pub(crate) sources: String,
    pub(crate) ptx: String,
    pub(crate) cubins: Vec<ManifestCubin>,
}

#[derive(Debug, PartialEq, Eq)]
pub(crate) struct ManifestCubin {
    pub(crate) arch: CubinArch,
    pub(crate) sha256: String,
    pub(crate) ptx: String,
}

impl Manifest {
    pub(crate) fn render(&self, project: &Project) -> String {
        let command = project.command;
        let mut text = format!(
            "# generated by `{command} build`; checked by `{command} check`\ncuda-oxide = {}\ntoolchain = {}\n",
            project.pins.cuda_oxide_rev, project.pins.cuda_oxide_nightly
        );
        if let Some(version) = &self.ptxas {
            let _ = writeln!(text, "ptxas = {version}");
        }

        if let Some(flags) = &self.ptxas_flags {
            let _ = writeln!(text, "ptxas-flags = {flags}");
        }

        for variant in &self.variants {
            let _ = write!(
                text,
                "\n[{}]\ntarget = {}\nsources = {}\nptx = {}\n",
                variant.tier.name(),
                variant.tier.arch(),
                variant.sources,
                variant.ptx
            );
            for cubin in &variant.cubins {
                let _ = writeln!(
                    text,
                    "cubin.{} = {} {}",
                    cubin.arch.name(),
                    cubin.sha256,
                    cubin.ptx
                );
            }
        }

        text
    }

    /// Parses a manifest whose cubins must use one of `arches`
    pub(crate) fn parse(text: &str, arches: &[CubinArch]) -> Result<Self> {
        let mut header = BTreeMap::new();
        let mut sections: Vec<(&str, BTreeMap<&str, &str>)> = Vec::new();
        for line in text.lines().map(str::trim) {
            if line.is_empty() || line.starts_with('#') {
                continue;
            }

            if let Some(name) = line
                .strip_prefix('[')
                .and_then(|line| line.strip_suffix(']'))
            {
                sections.push((name, BTreeMap::new()));
                continue;
            }

            let (key, value) = line
                .split_once('=')
                .ok_or_else(|| eyre!("invalid manifest line `{line}`"))?;
            let fields = sections
                .last_mut()
                .map(|(_, fields)| fields)
                .unwrap_or(&mut header);
            if fields.insert(key.trim(), value.trim()).is_some() {
                bail!("duplicate manifest field `{}`", key.trim());
            }
        }

        let variants = sections
            .into_iter()
            .map(|(name, fields)| ManifestVariant::parse(name, &fields, arches))
            .collect::<Result<_>>()?;
        Ok(Self {
            ptxas: header.get("ptxas").map(|value| value.to_string()),
            ptxas_flags: header.get("ptxas-flags").map(|value| value.to_string()),
            variants,
        })
    }
}

impl ManifestVariant {
    fn parse(name: &str, fields: &BTreeMap<&str, &str>, arches: &[CubinArch]) -> Result<Self> {
        let tier =
            Tier::parse(name).ok_or_else(|| eyre!("manifest has unknown tier `[{name}]`"))?;
        let field = |key: &str| {
            fields
                .get(key)
                .map(|value| value.to_string())
                .ok_or_else(|| eyre!("manifest section `[{name}]` has no `{key}` field"))
        };

        let target = field("target")?;
        if target != tier.arch() {
            bail!(
                "manifest section `[{name}]` has target `{target}`, expected `{}`",
                tier.arch()
            );
        }

        let mut cubins = Vec::new();
        for (key, value) in fields {
            let Some(arch) = key.strip_prefix("cubin.") else {
                continue;
            };
            let arch = CubinArch::parse(arch, arches)
                .ok_or_else(|| eyre!("unknown cubin arch `{arch}`"))?;
            let hashes: Vec<_> = value.split_whitespace().collect();
            if hashes.len() != 2 {
                bail!("manifest `{key}` needs cubin sha256 and source PTX sha256");
            }

            cubins.push(ManifestCubin {
                arch,
                sha256: hashes[0].into(),
                ptx: hashes[1].into(),
            });
        }

        cubins.sort_by_key(|cubin| cubin.arch.0);
        Ok(Self {
            tier,
            sources: field("sources")?,
            ptx: field("ptx")?,
            cubins,
        })
    }
}
